type DialogControlInput = Omit<ControlInput, 'region'> & { region?: string }

function dialogControl(input: DialogControlInput): FluentMockControl {
  return makeControl({
    ...input,
    region: input.region ?? '模拟窗口',
  })
}

function makeDialog(
  id: string,
  title: string,
  module: string,
  subtitle: string,
  controls: DialogControlInput[],
): FluentMockDialog {
  return {
    id,
    title,
    module,
    subtitle,
    controls: controls.map((control) =>
      dialogControl({
        ...control,
        parentId: control.parentId ?? id,
      }),
    ),
  }
}

