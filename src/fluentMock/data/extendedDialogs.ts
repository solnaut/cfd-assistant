import type { FluentMockDialog } from '../fluentTypes'
import { makeControl, type ControlInput } from './controlHelpers'

function makeDialog(
  id: string,
  title: string,
  module: string,
  subtitle: string,
  controls: Array<Omit<ControlInput, 'region'>>,
): FluentMockDialog {
  return {
    id,
    title,
    module,
    subtitle,
    controls: controls.map((control) =>
      makeControl({
        ...control,
        region: '模拟窗口',
        parentId: control.parentId ?? id,
      }),
    ),
  }
}

