export function resolveDialogProfile(dialogId?: string): DialogTeachingProfile | undefined {
  if (!dialogId) return undefined
  if (exactProfiles[dialogId]) return exactProfiles[dialogId]
  for (const [pattern, profile] of filePatternDescriptions) {
    if (pattern.test(dialogId)) return profile
  }
  return undefined
}

