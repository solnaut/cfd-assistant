const labels = new Map(
  terms.flatMap(([en, zh]) => [[en.toLowerCase(), [en, zh]], [zh.toLowerCase(), [en, zh]]] as const),
)

export function labelIn(language: FluentLanguage, term: string): string {
  const key = aliases.get(term) ?? term
  const entry = labels.get(key.toLowerCase())
  if (!entry) return term

  const [en, zh] = entry
  if (language === 'both') return en + ' · ' + zh
  return language === 'en' ? en : zh
}
